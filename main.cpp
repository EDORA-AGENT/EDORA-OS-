#include "edora.h"

// ======================================================
//                    EDORA OS
//                    MAIN ENTRY
// ======================================================

bool running = true;

bool isRoot = false;

string username = "user";

fs::path edoraRoot;

fs::path currentPath;

char currentDrive = 'C';

// ======================================================
//                         MAIN
// ======================================================

int main()
{
    // ------------------------------------------
    // EDORA ROOT DIRECTORY
    // ------------------------------------------

    edoraRoot = fs::current_path() / "EDORA_DRIVES";

    // ------------------------------------------
    // INITIALIZE KERNEL
    // ------------------------------------------

    kernelInit();

    // ------------------------------------------
    // INITIALIZE FILESYSTEM
    // ------------------------------------------

    filesystemInit();

    // ------------------------------------------
    // START SHELL
    // ------------------------------------------

    shellStart();

    // ------------------------------------------
    // MAIN LOOP
    // ------------------------------------------

    while (running)
    {
        shellLoop();
    }

    // ------------------------------------------
    // SHUTDOWN
    // ------------------------------------------

    kernelShutdown();

    return 0;
}