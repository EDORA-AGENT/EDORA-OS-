static unsigned char multiply(unsigned char a, unsigned char b)
{
    unsigned char result = 0;
    while (b)
    {
        if (b & 1) result ^= a;
        a = static_cast<unsigned char>((a & 0x80) ? (a << 1) ^ 0x1B : a << 1);
        b >>= 1;
    }
    return result;
}

static unsigned char rcon(unsigned int index)
{
    unsigned char value = 1;
    for (unsigned int count = 1; count < index; ++count)
        value = multiply(value, 2);
    return value;
}

static void expand_key()
{
    for (int index = 0; index < 32; ++index)
        round_keys[index] = key[index];

    for (int word = 8; word < 60; ++word)
    {
        unsigned char temp[4];
        for (int byte = 0; byte < 4; ++byte)
            temp[byte] = round_keys[(word - 1) * 4 + byte];

        if (word % 8 == 0)
        {
            unsigned char first = temp[0];
            temp[0] = sbox[temp[1]];
            temp[1] = sbox[temp[2]];
            temp[2] = sbox[temp[3]];
            temp[3] = sbox[first];
            temp[0] ^= rcon(word / 8);
        }
        else if (word % 8 == 4)
        {
            for (int byte = 0; byte < 4; ++byte)
                temp[byte] = sbox[temp[byte]];
        }

        for (int byte = 0; byte < 4; ++byte)
            round_keys[word * 4 + byte] = round_keys[(word - 8) * 4 + byte] ^ temp[byte];
    }
}

static void add_key(unsigned char* state, int round)
{
    for (int index = 0; index < 16; ++index)
        state[index] ^= round_keys[round * 16 + index];
}

static void inverse_shift(unsigned char* state)
{
    unsigned char copy[16];
    for (int index = 0; index < 16; ++index)
        copy[index] = state[index];
    for (int row = 0; row < 4; ++row)
        for (int column = 0; column < 4; ++column)
            state[column * 4 + row] = copy[((column - row + 4) % 4) * 4 + row];
}

static void inverse_substitute(unsigned char* state)
{
    for (int index = 0; index < 16; ++index)
        state[index] = inv_sbox[state[index]];
}

static void inverse_mix(unsigned char* state)
{
    for (int column = 0; column < 4; ++column)
    {
        unsigned char* value = state + column * 4;
        unsigned char a = value[0], b = value[1], c = value[2], d = value[3];
        value[0] = multiply(a, 0x0E) ^ multiply(b, 0x0B) ^ multiply(c, 0x0D) ^ multiply(d, 0x09);
        value[1] = multiply(a, 0x09) ^ multiply(b, 0x0E) ^ multiply(c, 0x0B) ^ multiply(d, 0x0D);
        value[2] = multiply(a, 0x0D) ^ multiply(b, 0x09) ^ multiply(c, 0x0E) ^ multiply(d, 0x0B);
        value[3] = multiply(a, 0x0B) ^ multiply(b, 0x0D) ^ multiply(c, 0x09) ^ multiply(d, 0x0E);
    }
}

static void decrypt_block(const unsigned char* input, unsigned char* output)
{
    unsigned char state[16];
    for (int index = 0; index < 16; ++index)
        state[index] = input[index];

    add_key(state, 14);
    for (int round = 13; round > 0; --round)
    {
        inverse_shift(state);
        inverse_substitute(state);
        add_key(state, round);
        inverse_mix(state);
    }
    inverse_shift(state);
    inverse_substitute(state);
    add_key(state, 0);

    for (int index = 0; index < 16; ++index)
        output[index] = state[index];
}

static bool equals(const char* left, const char* right)
{
    while (*left && *right && *left == *right)
    {
        ++left;
        ++right;
    }
    return *left == 0 && *right == 0;
}

static void read_line(const char* prompt, char* output, int limit, bool masked)
{
    vga_print(prompt);
    int length = 0;
    while (true)
    {
        char character = keyboard_getchar();
        if (character == '\n')
        {
            output[length] = 0;
            vga_print("\n");
            return;
        }
        if (character == '\b')
        {
            if (length > 0)
            {
                --length;
                vga_putc('\b');
            }
            continue;
        }
        if (length < limit - 1)
        {
            output[length++] = character;
            vga_putc(masked ? '*' : character);
        }
    }
}

void auth_init()
{
    unsigned char decrypted[16];
    unsigned int features = system_cpu_features();

    expand_key();
    decrypt_block(encrypted_login, decrypted);
    for (int index = 0; index < 16; ++index)
        decrypted_login[index] = static_cast<char>(decrypted[index]);
    decrypted_login[15] = 0;
    encrypted_record_valid = equals(decrypted_login, "root:1234:ADMIN");

    if ((features & (1u << 26)) && (features & (1u << 6)) && (features & (1u << 9)))
        current_permission = PERMISSION_KERNEL;
    else if (features & (1u << 26))
        current_permission = PERMISSION_ADMIN;
    else if (features & 1u)
        current_permission = PERMISSION_USER;
    else
        current_permission = PERMISSION_GUEST;
}

bool auth_login()
{
    char username[16];
    char password[16];

    vga_clear();
    vga_set_color(15, 1);
    vga_set_cursor(27, 4);
    vga_print("EDORA LOGIN");
    vga_set_color(15, 0);
    vga_set_cursor(22, 8);
    read_line("Username: ", username, 16, false);
    vga_set_cursor(22, 10);
    read_line("Password: ", password, 16, true);

    bool valid = encrypted_record_valid && equals(username, "root") && equals(password, "1234");
    if (valid && current_permission >= PERMISSION_ADMIN)
    {
        vga_print("Login accepted. Permission: ");
        vga_print(auth_permission_name());
        vga_print("\n");
        return true;
    }

    vga_print("Login denied: invalid credentials or CPU permission level.\n");
    return false;
}

PermissionLevel auth_permission()
{
    return current_permission;
}

const char* auth_username()
{
    return "root";
}

const char* auth_permission_name()
{
    if (current_permission == PERMISSION_KERNEL) return "KERNEL";
    if (current_permission == PERMISSION_ADMIN) return "ADMIN";
    if (current_permission == PERMISSION_USER) return "USER";
    return "GUEST";
}
